import { expect as baseExpect, test } from '@playwright/test';
const expect = baseExpect.configure({ timeout: 15_000 });
import { randomUUID } from 'node:crypto';
import { db } from '../../packages/database/src/index';

const isolated = process.env.DATABASE_URL?.split('?')[0].endsWith('/pactra_test') && process.env.TEST_DATABASE_URL?.split('?')[0].endsWith('/pactra_test');
test.describe('persistent seller demo', () => {
  test.skip(!isolated, 'This database-writing walkthrough requires the isolated pactra_test database.');
  const sellerId = 'judge_e2e_' + randomUUID();
  const existingName = 'Existing judge field guide ' + sellerId.slice(-6);
  const productName = 'New judge field guide ' + sellerId.slice(-6);
  let roomId: string | undefined;
  test.beforeAll(async () => {
    await db.seller.create({ data: { id: sellerId, name: 'Judge flow test shop', strategy: 'price_first', warrantyMonths: 12, standardCents: 500, standardDays: 4, expressCents: 1000, expressDays: 2 } });
    const product = await db.product.create({ data: { id: randomUUID(), name: existingName, brand: 'Test fixture', role: 'books', description: 'An isolated browser test product for the seller flow.', images: ['https://images.example.test/judge-guide.jpg'], isDemo: false, score: 50, video: 'not_applicable', audio: 'not_applicable', mount: 'not_applicable' } });
    await db.listing.create({ data: { id: randomUUID(), sellerId, productId: product.id, listCents: 3400, floorCents: 2500, onHand: 8 } });
  });
  test.afterAll(async () => {
    if (roomId) {
      await db.job.deleteMany({ where: { roomId } });
      await db.roomEvent.deleteMany({ where: { roomId } });
      await db.shoppingSession.deleteMany({ where: { id: roomId } });
    }
    const productIds = (await db.listing.findMany({ where: { sellerId }, select: { productId: true } })).map(l => l.productId);
    await db.sellerPolicyVersion.deleteMany({ where: { sellerId } });
    await db.listing.deleteMany({ where: { sellerId } });
    await db.seller.deleteMany({ where: { id: sellerId } });
    await db.product.deleteMany({ where: { id: { in: productIds } } });
    await db.$disconnect();
  });
  test('one click opens real edits that survive refresh, publish in the market and enter negotiation', async ({ page }) => {
    test.setTimeout(120_000);
    const pageErrors: string[] = []; page.on('pageerror', error => pageErrors.push(error.message));
    await page.goto('/');
    await page.getByRole('link', { name: 'Try the seller workspace', exact: true }).first().click();
    await expect(page.getByRole('region', { name: 'Shared seller demo', exact: true })).toBeVisible({ timeout: 30_000 });
    await expect(page.getByLabel('Shop access code')).toHaveCount(0);
    const status = await (await page.request.get('/api/owner/session')).json();
    expect(status).toMatchObject({ authenticated: true, demoSession: true });
    const cookie = (await page.context().cookies()).find(c => c.name === 'pactra_owner');
    expect(cookie).toMatchObject({ httpOnly: true, sameSite: 'Strict', path: '/api/owner' });
    await page.getByRole('combobox', { name: 'Current shop', exact: true }).selectOption(sellerId);
    await page.getByRole('navigation', { name: 'Seller tools' }).getByRole('link', { name: /Products/ }).click();
    await page.getByRole('button', { name: 'Edit ' + existingName, exact: true }).click();
    await page.getByLabel('Asking price · USD').fill('35');
    await page.getByLabel('I have checked this product').check();
    await page.getByRole('button', { name: 'Publish product', exact: true }).click();
    await expect(page.getByText('Product saved. Drafts stay private until you publish them.', { exact: true })).toBeVisible();
    expect(await db.listing.findFirst({ where: { sellerId, product: { name: existingName } } })).toMatchObject({ listCents: 3500 });
    await page.reload();
    await expect(page.getByRole('combobox', { name: 'Current shop', exact: true })).toHaveValue(sellerId);
    await expect(page.getByRole('table')).toContainText('$35');
    await page.getByRole('button', { name: 'Add product', exact: true }).click();
    await page.getByLabel('Product photos', { exact: true }).fill('https://images.example.test/judge-guide.jpg');
    await page.getByLabel('Product name', { exact: true }).fill(productName);
    await page.getByLabel('Brand', { exact: true }).fill('Test fixture');
    await page.getByLabel('Category', { exact: true }).fill('books');
    await page.getByLabel('Product details', { exact: true }).fill('A published test field guide, created through the real seller form.');
    await page.getByLabel('Asking price · USD').fill('40');
    await page.getByLabel('Private minimum · USD').fill('30');
    await page.getByLabel('Quantity in stock').fill('8');
    await page.getByLabel('Listing status').selectOption('active');
    await page.getByLabel('I have checked this product').check();
    await page.getByRole('button', { name: 'Publish product', exact: true }).click();
    await expect(page.getByText('Product saved. Drafts stay private until you publish them.', { exact: true })).toBeVisible();
    const added = await db.listing.findFirstOrThrow({ where: { sellerId, product: { name: productName } } });
    expect(added).toMatchObject({ listCents: 4000, floorCents: 3000, onHand: 8, status: 'active' });
    await page.getByRole('navigation', { name: 'Seller tools' }).getByRole('link', { name: 'Agent rules' }).click();
    await page.getByLabel('Standard arrival · days').fill('3');
    await page.getByLabel('Standard delivery · USD').fill('6');
    await page.getByLabel('What changed?').fill('Browser check of persistent delivery rules');
    await page.getByRole('button', { name: 'Save my rules', exact: true }).click();
    await expect(page.getByText('Your agent’s rules are saved. New offers will use them.', { exact: true })).toBeVisible();
    expect(await db.seller.findUnique({ where: { id: sellerId } })).toMatchObject({ standardCents: 600, standardDays: 3 });
    await page.goto('/');
    const card = page.getByRole('article').filter({ has: page.getByRole('heading', { name: productName, exact: true }) });
    await expect(card).toBeVisible();
    await expect(card).toContainText('$40.00');
    await card.getByRole('link', { name: 'Negotiate this item' }).click();
    await page.getByRole('spinbutton', { name: 'Total budget (including delivery)' }).fill('60');
    await page.getByRole('button', { name: 'Start my negotiation', exact: true }).click();
    await expect(page).toHaveURL(/\/rooms\/[^/]+$/);
    roomId = new URL(page.url()).pathname.split('/').pop();
    const room = await db.shoppingSession.findUniqueOrThrow({ where: { id: roomId } });
    expect(room.brief).toMatchObject({ items: [{ productId: added.productId, quantity: 1 }] });
    expect(await db.job.findFirst({ where: { roomId } })).not.toBeNull();
    const forged = await page.request.post('/api/owner/demo-login', { data: {}, headers: { Origin: 'https://not-pactra.example' } });
    expect(forged.status()).toBe(403);
    await page.goto('/seller-demo?shop=' + encodeURIComponent(sellerId) + '#orders');
    await page.getByRole('combobox', { name: 'Current shop', exact: true }).selectOption(sellerId);
    await expect(page.getByRole('region', { name: 'Orders and payments', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Sign out', exact: true }).click();
    expect((await page.request.get('/api/owner/sellers')).status()).toBe(401);
    expect(pageErrors).toEqual([]);
  });
});
